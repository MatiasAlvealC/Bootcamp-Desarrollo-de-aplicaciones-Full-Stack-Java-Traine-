package Ejercicio1;

public class CambiarWhile {

	public static void main(String[] args) {
		/*
		 * Codigo a cambiar
		 * int i = 0;
		 * while (i<50){
		 * 	i+=1;
		 * System.out.printf("Iteracion %d\n",i);
		 * }
		 */
		
		int i = 0;
		
		do {
			i++;
			System.out.printf("Iteración %d\n",i);
		} while (i<50);
		
	}

}
